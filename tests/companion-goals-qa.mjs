import assert from 'node:assert/strict';
import fs from 'node:fs';
import {petLevel,evolutionGoal,goalView,celebrationToken,firstGoal} from '../assets/companion-goals-state-20261004.js';
const p={species:'moss-hornling',masteryPoints:100,petLevels:{'moss-hornling':1}};
assert.equal(evolutionGoal(p,p.species,3).cost,140);
assert.equal(evolutionGoal(p,p.species,3).remaining,40);
assert.equal(evolutionGoal(p,p.species,2).ready,true);
assert.equal(evolutionGoal(p,p.species,2).unlocked,false);
assert.equal(evolutionGoal({...p,masteryPoints:49},p.species,2).ready,false);
assert.equal(evolutionGoal({...p,petLevels:{'moss-hornling':2}},p.species,3).cost,90);
assert.equal(p.masteryPoints,100);
assert.equal(petLevel({species:'inkling',highestStage:4},'inkling'),4);
assert.equal(petLevel({species:'inkling',highestStage:4},'moss-hornling'),1);
assert.equal(firstGoal({...p,petLevels:{'moss-hornling':5}}),null);
const state={unlockedOutfits:[],unlockedScenes:[],xp:600,studyDays:3};
const cat={outfits:[{id:'cardigan',name:'Cardigan',needIf:{xp:600,studyDays:3}}],scenes:[{id:'courtyard',name:'Courtyard',needIf:{xp:700}}],stats:x=>x,requirements:(rule,s)=>Object.entries(rule||{}).map(([key,target])=>({key,label:key,current:s[key]||0,target,met:(s[key]||0)>=target}))};
const before=JSON.stringify(state);
const locked=goalView({kind:'outfit',id:'cardigan'},state,p,cat);
assert.equal(locked.ready,false,'requirements alone never grant or equip rewards');
assert.equal(celebrationToken(locked),null);
const ready=goalView({kind:'outfit',id:'cardigan'},{...state,unlockedOutfits:['cardigan']},p,cat);
assert.equal(ready.ready,true);
assert.equal(celebrationToken(ready),'outfit:cardigan::unlocked');
assert.equal(goalView({kind:'scene',id:'courtyard'},state,p,cat).ready,false);
assert.equal(goalView({kind:'scene',id:'courtyard'},{...state,unlockedScenes:['courtyard']},p,cat).ready,true);
assert.equal(JSON.stringify(state),before);
assert.equal(goalView({kind:'outfit',id:'unknown'},state,p,cat),null);
const runtime=fs.readFileSync('assets/companion-experience-20261004.js','utf8');
assert.ok(!runtime.includes('store.setState'));
assert.ok(runtime.includes('s.equipOutfit(v.id)')&&runtime.includes('s.equipScene(v.id)'));
const loader=fs.readFileSync('assessment-link.js','utf8');
assert.ok(loader.startsWith("if(!/^\\/(pet|assessment)(\\/|$)/.test(location.pathname))"),'standalone pages cannot import React root');
console.log('Companion goals: 21 checks passed; cumulative MP, unlock authority, no reward mutation, standalone guard.');
