import assert from 'node:assert/strict';
import {mistakeReviewTask,creditMistakeReview} from '../assets/mistake-review-plan-20261003.js';
const state={today:'2026-10-03',daily:[],reviews:{},seenTotal:{},seenCorrect:{}};
for(let i=0;i<14;i++)state.reviews['wrong'+i]={subject:'french',topicId:'fr-y8-s02-weather-activities-and-opinions',wrong:true,last:'2026-10-02',due:'2026-10-04'};
state.reviews.today={subject:'french',topicId:'fr-y8-topic',wrong:true,last:'2026-10-03'};
state.reviews.correct={subject:'french',topicId:'fr-y8-topic',wrong:false,last:'2026-10-01'};
let task=mistakeReviewTask(state);
assert.equal(task.target,10);assert.equal(task.reviewYear,8);
assert.ok(!task.reviewQuestionIds.includes('today'));assert.ok(!task.reviewQuestionIds.includes('correct'));
assert.strictEqual(creditMistakeReview(task,task.reviewQuestionIds[0],false,state.today),task);
task=creditMistakeReview(task,task.reviewQuestionIds[0],true,state.today);
assert.equal(task.progress,1);assert.equal(creditMistakeReview(task,task.reviewQuestionIds[0],true,state.today).progress,1);
state.daily=[task];state.reviews={};
assert.deepEqual(mistakeReviewTask(state),task,'Closing or clearing reviews must retain the same assigned questions and progress');
for(const id of task.reviewQuestionIds)task=creditMistakeReview(task,id,true,state.today);
assert.equal(task.progress,10);
assert.equal(mistakeReviewTask({...state,today:'2026-10-04'}).progress,1,'No unresolved old mistakes is automatically clear');
const legacy=mistakeReviewTask({...state,daily:[],reviews:{old:{subject:'latin',topicId:'la-y9-topic',stage:1,last:'2026-10-01'}},seenTotal:{old:2},seenCorrect:{old:1}});
assert.deepEqual(legacy.reviewQuestionIds,['old']);assert.equal(legacy.reviewYear,9);
console.log('Mistake review task passed: yesterday/older only, cap, correct-only unique credit, locked plan, reload persistence, empty day and legacy mistakes.');
